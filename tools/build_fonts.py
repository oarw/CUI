#!/usr/bin/env python3
"""Regenerates the embedded font data used by CUI.

Inputs (already subset, committed in assets/fonts):
    Inter-Regular.ttf, Inter-Medium.ttf, Geist-Medium.ttf, GeistMono-Regular.ttf
Icon font (optional input, the full Lucide font):
    python3 tools/build_fonts.py --lucide path/to/lucide.ttf --codepoints path/to/codepoints.json

Outputs:
    assets/fonts/Lucide-CUI.ttf     (icon subset, only when --lucide is given)
    include/cui/cui_icons.h         (only when --lucide is given)
    src/cui_font_data.c             (always)

Requires: pip install fonttools
"""
