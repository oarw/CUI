def c_ident(name):
    return name.upper().replace("-", "_")


def utf8_escape(cp):
    return "".join("\\x%02x" % b for b in chr(cp).encode("utf-8"))


def build_icons(lucide, codepoints_path):
    cps = json.load(open(codepoints_path))
    missing = [n for n in ICONS if n not in cps]
    if missing:
        sys.exit("missing icons: %s" % missing)
    unicodes = ",".join("U+%04X" % cps[n] for n in ICONS)
    out = os.path.join(FONTS, "Lucide-CUI.ttf")
    subprocess.check_call(["pyftsubset", lucide, "--unicodes=" + unicodes,
                           "--output-file=" + out, "--no-hinting",
                           "--layout-features=", "--name-IDs=*"])
    hdr = os.path.join(ROOT, "include", "cui", "cui_icons.h")
    with open(hdr, "w") as f:
        f.write("/* Generated by tools/build_fonts.py. Do not edit.\n")
        f.write(" * Lucide icons (ISC license, https://lucide.dev).\n")
        f.write(" * Each icon is a UTF-8 string, so it can be used on its own or inside\n")
        f.write(" * any label: cui_button(ui, CUI_ICON_PLUS \" New project\"). */\n")
        f.write("#ifndef CUI_ICONS_H\n#define CUI_ICONS_H\n\n")
        for n in ICONS:
            f.write('#define CUI_ICON_%-24s "%s"\n' % (c_ident(n), utf8_escape(cps[n])))
        f.write("\n#endif /* CUI_ICONS_H */\n")
    # the icon sheet used by tests/component_shots.c
    with open(os.path.join(ROOT, "tests", "icon_list.h"), "w") as f:
        f.write("/* Generated from cui_icons.h for the icon sheet. */\n")
        f.write("static const struct { const char *name, *icon; } icon_list[] = {\n")
        for n in ICONS:
            f.write('    { "%s", CUI_ICON_%s },\n' % (n, c_ident(n)))
        f.write("};\n")
    # the table in docs/icons.md
    doc = os.path.join(ROOT, "docs", "icons.md")
    text = open(doc).read()
    import re
    rows = ["| | | | |", "|---|---|---|---|"]
    names = ["`CUI_ICON_%s`" % c_ident(n) for n in ICONS]
    for i in range(0, len(names), 4):
        cells = names[i:i + 4] + [""] * (4 - len(names[i:i + 4]))
        rows.append("| " + " | ".join(cells) + " |")
    text = re.sub(r"\| \| \| \| \|\n\|---\|---\|---\|---\|\n(?:\|.*\|\n)*", "\n".join(rows) + "\n", text, count=1)
    text = re.sub(r"CUI embeds \d+ icons", "CUI embeds %d icons" % len(ICONS), text)
    open(doc, "w").write(text)
    print("wrote", out, hdr, "tests/icon_list.h and docs/icons.md")


def deflate(data):
    """Raw DEFLATE stream. Uses zopfli (pip install zopfli) when available,
    which packs about 4% tighter than zlib."""
    try:
        import zopfli.zlib
        z = zopfli.zlib.compress(data, numiterations=50)
    except ImportError:
        import zlib
        z = zlib.compress(data, 9)
    return z[2:-4]   # strip the zlib header and checksum


def emit_array(f, name, path):
    raw = open(path, "rb").read()
    data = deflate(raw)
    f.write("const unsigned int %s_size = %d;      /* unpacked */\n" % (name, len(raw)))
    f.write("const unsigned int %s_packed = %d;    /* raw DEFLATE */\n" % (name, len(data)))
    f.write("const unsigned char %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 20):
        f.write("  " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n\n")


def build_data():
    out = os.path.join(ROOT, "src", "cui_font_data.c")
    with open(out, "w") as f:
        f.write("/* Generated by tools/build_fonts.py. Do not edit.\n")
        f.write(" * Inter and Geist: SIL Open Font License 1.1. Lucide: ISC.\n")
        f.write(" * See assets/fonts for the license texts.\n")
        f.write(" * Stored as raw DEFLATE streams and unpacked when a context is created. */\n")
        f.write("#include \"cui_internal.h\"\n\n")
        f.write("#ifndef CUI_NO_DEFAULT_FONTS\n\n")
        f.write("#ifndef CUI_ICON_FONT_ONLY\n\n")
        for name, file in [("cui_font_inter_regular", "Inter-Regular.ttf"),
                           ("cui_font_inter_medium", "Inter-Medium.ttf"),
                           ("cui_font_geist_medium", "Geist-Medium.ttf"),
                           ("cui_font_geist_mono", "GeistMono-Regular.ttf"),
                           ("cui_font_lucide", "Lucide-CUI.ttf")]:
            if name == "cui_font_lucide":
                f.write("#endif /* CUI_ICON_FONT_ONLY */\n\n")
            emit_array(f, name, os.path.join(FONTS, file))
        f.write("#endif\n")
    print("wrote", out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--lucide")
    ap.add_argument("--codepoints")
    a = ap.parse_args()
    if a.lucide:
        build_icons(a.lucide, a.codepoints)
    build_data()
